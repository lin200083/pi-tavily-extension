/** Normalize a `country` value and resolve common aliases. */
export function normalizeCountry(value: string): string {
  return value.trim().toLowerCase().replace(/\s+/g, " ");
}

/**
 * Resolve a `country` value to the string sent to Tavily.
 *
 * Aliases map to their canonical name; a value already in the enum is sent
 * as-is; anything else is passed through unchanged so the API (which knows its
 * current enum) can accept or reject it. Returns undefined only for empty
 * input.
 */
export function resolveCountry(value: string): string | undefined {
  const normalized = normalizeCountry(value);
  if (!normalized) return undefined;
  const alias = COUNTRY_ALIASES[normalized];
  if (alias) return alias;
  return normalized;
}
